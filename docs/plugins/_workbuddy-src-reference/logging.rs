//! WorkBuddy 模块的日志出口。
//!
//! ── 为什么单独一个文件 ─────────────────────────────────────
//! 两条约束都要在**写日志的地方**兑现，而不是靠调用方自觉：
//!   1. **永远不打印凭证**。本模块处理的是 accessToken / refreshToken，一旦
//!      顺手 `{:?}` 打到日志里，就会跟着日志文件被用户发到群里。因此这里只提供
//!      `info` / `warn` 两个收 `&str` 的函数 —— 没有 `Debug` 通道，想打印结构体
//!      必须先自己拼成脱敏字符串。
//!   2. 统一前缀 `[workbuddy]`：日志文件里混着几十个子系统的输出，没有前缀的
//!      「登录失败」根本看不出是谁失败。
//!
//! 用 `log` 门面而不是 `eprintln!`：桌面端（tauri）已经把 `log` 接到文件与
//! devtools；`eprintln!` 在发布版没有控制台，等于写进了虚空。

/// 值得留痕的正常事件（登录成功、目录刷新、账号增删）。
pub fn info(message: &str) {
    log::info!("[workbuddy] {message}");
}

/// 不影响主流程但需要能查的异常（单条记录解不开、目录刷新失败回落到缓存）。
pub fn warn(message: &str) {
    log::warn!("[workbuddy] {message}");
}
