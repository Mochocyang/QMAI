export const DE_AI_GENERATION_RULES = `## 反 AI 腔硬约束

### 词法
- 禁总结腔：这一切、显然、事实上、实际上、毫无疑问、无可否认。
- 禁解释腔：其实、说白了、换句话说、简单来说、通俗点讲、某种程度上。
- 禁模板句首：与此同时、紧接着、就在这时、恰在此时、正当此刻。
- 禁空洞形容：复杂、微妙、深刻、独特、特殊——没落到可见处就不要写。
- 转折限用：然而/但是/不过/可是，同一段最多一个，不要每段都用。
- AI 特征词限用（不是全禁）：似乎、仿佛、如同、宛如、犹如、不由得、不禁。
- 禁烂句：目光交汇的瞬间、空气仿佛凝固、心中五味杂陈、眼神变得坚定。

### 句式
- 不写「不是 A，而是 B」这种二分对照壳；要比就摆两个具体事实。
- 不把「概念：解释」当固定模板，别连着几段都用冒号起头。
- 路标词限用：首先/其次/最后/总之/综上/由此可见 当**段落结构词**连着用时，全章不超过两个
  （指这种「起段路标」用法，不是禁用「最后」这个词本身）。

### 叙事
- 不解释动机：别写「他这么做是因为……」，让动作和后果自己说。
- 不总结情绪：别写「她感到失望/欣慰/复杂」，换成动作、生理反应或环境。
- 段尾不补抽象结论、不为每段升华；事说完就收。
- 拒绝无效热闹：气氛循环、重复心理、重复打趣赶路都是同一层意思的第二遍，删。
- 不单手法循环：整章别只剩对线、独白或打斗一种形式。
- 同义反复、连续空形容词、三连以上排比，只留最有信息量的一处。

### 正面替换
- 抽象换成可见动作：不写「他很生气」，写「他拍桌而起」。
- 长句拆开：不写「他看着她，眼神复杂，既有愧疚又有无奈」，写「他看着她。愧疚。无奈。」
- 对话留毛边：说半句、答非所问、紧张时重复；不解释潜台词。

### 小说适配边界（不得忽略）
- 上面是地板不是净化器：副词与「似乎/仿佛/缓缓」在小说里可以是风格，不要硬删。
  （例外：上面烂句表里那几条固定搭配仍然不要写——它们是套话，不是风格。）
- 保留角色声线与必要停顿，不要为反 AI 味把句子写别扭、干瘪或像说明书。
- 读起来不像 AI，也不刻意反 AI。`

