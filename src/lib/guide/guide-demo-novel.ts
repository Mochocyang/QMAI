/**
 * 引导用的**内置示例小说**（零 Token）。
 *
 * 为什么要有它：新装用户往往还没拿到 API 密钥。如果引导的每一步都要求真实调用，
 * 第一步「生成大纲」就会卡死，整条流程走不完；用户会以为是软件坏了。
 *
 * 所以引导走的是**本地演示通路**：
 *   · 大纲：向导提交后在本地拼一份完整的大纲 Markdown 直接进对话，
 *     不请求任何模型；用户点「保存为大纲」仍走真实的写盘链路；
 *   · 章节：把示例正文写成一份**草稿章节**（`chapter_status: draft`，
 *     与 AI 生成草稿同一口径），用户能在真实编辑器里看到它、保存它、复制它。
 *
 * 关键约束：示例内容必须**看起来像真的**。如果只是「这里是示例大纲」一行占位，
 * 用户学不到任何东西，也没法拿它去试「提取记忆」「去 AI 味」。因此这里写的是
 * 一份结构完整、可以直接当模板改的短篇悬疑大纲与开篇正文。
 */

export interface GuideDemoNovel {
  /** 不带书名号的书名，例如「雾港夜航」。 */
  name: string
  /** 一句话题材，用于大纲里的定位。 */
  genre: string
  /** 第一章标题（不含「第1章」前缀）。 */
  chapterTitle: string
}

/**
 * 记住「这次引导用的是哪本示例书」。
 *
 * 引导是跨步骤、跨刷新进行的：创建小说那一步随机挑了《雾港夜航》，
 * 走到章节阶段（可能已经是第二天）时必须还是同一本，否则示例正文会写进
 * 另一本书、或者干脆找不到书。所以书名要落盘，而不是每次重新随机。
 */
export const GUIDE_DEMO_STORAGE_KEY = "qmai-guide-demo-v1"

/** 候选示例书。取随机一本，让每个用户看到的不是同一份内容。 */
export const GUIDE_DEMO_NOVELS: GuideDemoNovel[] = [
  { name: "雾港夜航", genre: "都市悬疑 · 轻奇幻", chapterTitle: "雾里的船" },
  { name: "长夜书店", genre: "都市奇谈 · 治愈", chapterTitle: "凌晨三点的客人" },
  { name: "归墟来信", genre: "悬疑推理 · 民国", chapterTitle: "第一封没有寄件人的信" },
  { name: "三月雪线", genre: "现实主义 · 成长", chapterTitle: "回山的第一天" },
  { name: "灯塔以北", genre: "海洋冒险 · 群像", chapterTitle: "值夜表上的第七个名字" },
  { name: "旧城回声", genre: "都市悬疑 · 双线", chapterTitle: "拆到第三面墙" },
]

/** 随机挑一本示例书。`random` 可注入，便于测试固定结果。 */
export function pickGuideDemoNovel(random: () => number = Math.random): GuideDemoNovel {
  const index = Math.floor(random() * GUIDE_DEMO_NOVELS.length)
  // random() 返回 1（或异常值）时 floor 会越界，夹一下比抛错安全。
  return GUIDE_DEMO_NOVELS[Math.min(Math.max(index, 0), GUIDE_DEMO_NOVELS.length - 1)]
}

/** 记住本次引导使用的示例书（按书名匹配内置清单，读到不认识的则丢弃）。 */
export function rememberGuideDemoNovel(novel: GuideDemoNovel): void {
  if (typeof localStorage === "undefined") return
  try {
    localStorage.setItem(GUIDE_DEMO_STORAGE_KEY, novel.name)
  } catch {
    /* 存不下也不影响当前这一轮：调用方手里已经有 novel 对象了。 */
  }
}

export function readGuideDemoNovel(): GuideDemoNovel | null {
  if (typeof localStorage === "undefined") return null
  try {
    const name = localStorage.getItem(GUIDE_DEMO_STORAGE_KEY)
    if (!name) return null
    return GUIDE_DEMO_NOVELS.find((novel) => novel.name === name) ?? null
  } catch {
    return null
  }
}

/** 向导里预填的「故事灵感 / 处理要求」。用户可以直接改成自己的。 */
export function buildGuideDemoInspiration(novel: GuideDemoNovel): string {
  return [
    `想写一个${novel.genre}的故事，暂定名《${novel.name}》。`,
    "主角是个二十七八岁的普通人，靠一份不起眼的夜班工作活着；他有一个不愿对人提起的旧伤。",
    "故事从一个反常的细节开始：他每天都会经过的地方，多了一样不该存在的东西。他越是查，越发现这件事和自己多年前的那次意外有关。",
    "希望节奏偏慢热，重氛围和细节，不要一开始就打斗；每章结尾留一个具体的钩子。",
  ].join("\n")
}

